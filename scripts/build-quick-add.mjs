// Bundles the app's quick add (web/src/adapters/quickAddServer.ts, which pulls in quickAdd.ts and its
// chrono date parser) into one script the server embeds and runs in Jint (PL-137), so the app and
// the task API read a line the same way.
//   node scripts/build-quick-add.mjs           write server/src/PeckList.Server/Api/quickadd.js
//   node scripts/build-quick-add.mjs --check   fail when the committed file is not what web/src makes (CI)

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';
import { root } from './versions.mjs';

const target = 'server/src/PeckList.Server/Api/quickadd.js';

// esbuild comes with the web app's build tools (a peer of vite), at the version the lockfile pins.
const fromWeb = createRequire(join(root, 'web', 'package.json'));
const esbuild = createRequire(fromWeb.resolve('vite/package.json'))('esbuild');

const result = await esbuild.build({
  absWorkingDir: root,
  entryPoints: ['web/src/adapters/quickAddServer.ts'],
  bundle: true,
  format: 'iife',
  // What Jint runs well; nothing newer is needed.
  target: 'es2020',
  minify: true,
  legalComments: 'eof',
  charset: 'utf8',
  write: false,
  logLevel: 'warning',
});
const header =
  '// Generated by scripts/build-quick-add.mjs from web/src/adapters/quickAddServer.ts: do not edit.\n' +
  `// esbuild ${esbuild.version}. Rebuild after changing quick add: node scripts/build-quick-add.mjs\n`;
const bundle = header + result.outputFiles[0].text.replaceAll('\r\n', '\n');

if (process.argv.includes('--check')) {
  let committed = '';
  try {
    committed = readFileSync(join(root, target), 'utf8').replaceAll('\r\n', '\n');
  } catch {
    // Missing: reported below.
  }
  if (committed !== bundle) {
    console.error(`${target} is not what web/src makes: run node scripts/build-quick-add.mjs`);
    process.exit(1);
  }
  console.log(`${target} matches web/src.`);
} else {
  writeFileSync(join(root, target), bundle);
  console.log(`wrote ${target} (${Math.round(bundle.length / 1024)} KB)`);
}
