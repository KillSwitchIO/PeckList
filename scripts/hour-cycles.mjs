// Which locales read a 12-hour clock, as ICU (the browser's Intl, Android's own) has it: the table
// the server decides an automatic clock from (schema 22), so pushes read the clock the app shows.
// ICU takes a locale's clock from its own data and falls back to the language's for a locale it has
// none for, so fr-US is 24-hour (French) and en-BR 12-hour (English): the region alone can't say.
//
//   node scripts/hour-cycles.mjs           rewrites server/src/PeckList.Core/Text/hour-cycles.json
//   node scripts/hour-cycles.mjs --check   exits 1 when this Node's ICU makes a different table
//
// web/src/core/hourCycles.test.ts runs the check, so a newer ICU that moves a locale shows up as a
// failing test, not a wrong push.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const TABLE = new URL('../server/src/PeckList.Core/Text/hour-cycles.json', import.meta.url);

const LETTERS = 'abcdefghijklmnopqrstuvwxyz';

const twelve = (tag) => {
  const cycle = new Intl.DateTimeFormat(tag, { hour: 'numeric' }).resolvedOptions().hourCycle;
  return cycle === 'h11' || cycle === 'h12';
};

/** Whether ICU has data of its own for exactly this tag (not a fallback to its language). */
const own = (tag) => {
  try {
    return new Intl.DateTimeFormat(tag).resolvedOptions().locale === tag;
  } catch {
    return false;
  }
};

/** The table: the 12-hour languages, and the locales whose clock differs from their language's. */
export function hourCycles() {
  const codes = [];
  for (const a of LETTERS)
    for (const b of LETTERS) {
      codes.push(a + b);
      for (const c of LETTERS) codes.push(a + b + c);
    }
  const languages = codes.filter(own);
  const regions = [];
  for (const a of LETTERS.toUpperCase()) for (const b of LETTERS.toUpperCase()) regions.push(a + b);
  regions.push('001', '150', '419');
  const result = { languages12: [], tags12: [], tags24: [] };
  for (const language of languages) {
    const base = twelve(language);
    if (base) result.languages12.push(language);
    // A language and a script ICU has data for, whose clock differs (zh-Hant, yue-Hans: Dev 1).
    for (const tag of [...regions, ...SCRIPTS].map((each) => `${language}-${each}`)) {
      if (!own(tag) || twelve(tag) === base) continue;
      (base ? result.tags24 : result.tags12).push(tag);
    }
  }
  return result;
}

/** The scripts CLDR's locales are written in (ISO 15924), for language-script locales. */
const SCRIPTS = (
  'Adlm Arab Armn Beng Bopo Cans Cher Cyrl Deva Dsrt Ethi Geor Grek Guru Hans Hant Hebr Hmnp ' +
  'Jpan Khmr Knda Kore Laoo Latn Mlym Mong Mtei Mymr Nkoo Olck Orya Rohg Shaw Sinh Syrc Taml ' +
  'Telu Tfng Thaa Tibt Vaii Yiii'
).split(' ');

export function tableText(table) {
  const note =
    "Generated by scripts/hour-cycles.mjs from ICU: do not edit. 12-hour languages, and the locales (language-region, language-script) whose clock differs from their language's; anything else reads its language's clock. A language ICU has no data for falls back to the browser's own default there, which the server can't know: it reads 24-hour, as ICU's root.";
  return `${JSON.stringify({ _note: note, ...table }, null, 2)}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const started = Date.now();
  const table = hourCycles();
  if (process.argv.includes('--check')) {
    if (readFileSync(TABLE, 'utf8').replace(/\r\n/g, '\n') !== tableText(table)) {
      console.error(
        `hour-cycles.json differs from what ICU ${process.versions.icu} says: run node scripts/hour-cycles.mjs and look at the change.`,
      );
      process.exit(1);
    }
    console.log(`hour-cycles.json matches ICU ${process.versions.icu}`);
    process.exit(0);
  }
  writeFileSync(TABLE, tableText(table));
  console.log(
    `hour-cycles.json: ${table.languages12.length} 12-hour languages, ${table.tags12.length} + ${table.tags24.length} locales apart, in ${Date.now() - started} ms (ICU ${process.versions.icu}, CLDR ${process.versions.cldr})`,
  );
}
