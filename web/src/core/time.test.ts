import { describe, expect, it } from 'vitest';
import { parseTime } from './time.ts';

describe('parseTime', () => {
  it.each([
    ['9', '09:00'],
    ['09', '09:00'],
    ['0', '00:00'],
    ['930', '09:30'],
    ['0930', '09:30'],
    ['9:30', '09:30'],
    ['9.30', '09:30'],
    ['09:05', '09:05'],
    ['22', '22:00'],
    ['2200', '22:00'],
    ['22:00', '22:00'],
    ['23:59', '23:59'],
    ['00:00', '00:00'],
    ['10pm', '22:00'],
    ['10 PM', '22:00'],
    ['10p', '22:00'],
    ['10:30pm', '22:30'],
    ['1030pm', '22:30'],
    ['10 p.m.', '22:00'],
    ['9am', '09:00'],
    ['9 a.m.', '09:00'],
    ['12am', '00:00'],
    ['12pm', '12:00'],
    ['12:15 am', '00:15'],
    ['  7  ', '07:00'],
  ])('%s -> %s', (input, expected) => {
    expect(parseTime(input)).toBe(expected);
  });

  it.each([
    '',
    '   ',
    '24',
    '25',
    '9:75',
    '960',
    '13pm',
    '0am',
    'noon',
    '9:3',
    '12345',
    '9::30',
    'pm',
  ])('rejects %j', (input) => {
    expect(parseTime(input)).toBeNull();
  });
});
